"""Build the 'Goodyear deals & warranties' section of site/index.html.

Reads data/goodyear.json and rewrites everything between the
<!-- GOODYEAR:START --> and <!-- GOODYEAR:END --> markers in site/index.html.
On the first run (no markers yet) the section is inserted straight after the
price-beat section that follows the workshop's own Deals section.

Promotions whose purchase_to date has passed (Hobart time) are left out
automatically, and a small inline script also hides any promotion card once
its end date passes in the visitor's browser.

Usage:  python3 tools/build_goodyear.py
"""
