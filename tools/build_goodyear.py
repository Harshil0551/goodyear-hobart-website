e = html.escape


def nice_date(iso):
    d = dt.date.fromisoformat(iso)
    return f"{d.day} {d.strftime('%B %Y')}"


def money(x):
    return f"${x:,.2f}".replace(".00", "")


def promo_card(p):
    items = [f"<li>Buy between {nice_date(p['purchase_from'])} and {nice_date(p['purchase_to'])}</li>"]
    if p.get("claim_by"):
        items.append(f"<li>Claim by {nice_date(p['claim_by'])}</li>")
    for c in p.get("conditions", []):
        items.append(f"<li>{e(c)}</li>")
    links = [f'<a href="{e(p["terms_url"])}" target="_blank" rel="noopener">Goodyear\'s terms and conditions</a>']
    if p.get("claim_url"):
        links.append(f'<a href="{e(p["claim_url"])}" target="_blank" rel="noopener">How to claim</a>')
    return (
        f'<div class="gy-promo rv" data-ends="{e(p["purchase_to"])}">'
        f'<span class="corner">GOODYEAR PROMOTION</span>'
        f'<h4>{e(p["title"])}</h4>'
        f'<p>{e(p["details"])}</p>'
        f'<ul>{"".join(items)}</ul>'
        f'<p class="gy-links">{" · ".join(links)}</p></div>'
    )


